/**
 * GET /api/v1/sync/events
 * 
 * Server-Sent Events (SSE) Real-Time Synchronization Stream:
 * Pushes instant updates to connected browser clients whenever:
 * - New messages are created or streamed
 * - Conversation titles or metadata change
 * - User preferences update on another device
 * - Notifications or agent tasks change state
 * 
 * Includes 15s keep-alive heartbeat and zero-memory-leak cleanup on client disconnect.
 */

import { NextRequest } from "next/server";
import { resolveAuthUser } from "@/lib/auth/serverAuth";
import { subscribeToSyncEvents } from "@/lib/sync/syncEngine";

export const dynamic = "force-dynamic";

export async function GET(req: NextRequest) {
  const user = await resolveAuthUser(req);
  if (!user) {
    return new Response(JSON.stringify({ code: "UNAUTHORIZED", message: "جلسة المستخدم غير صالحة" }), {
      status: 401,
      headers: { "Content-Type": "application/json" },
    });
  }

  const encoder = new TextEncoder();
  const deviceId = req.headers.get("x-device-id") || req.nextUrl.searchParams.get("deviceId");

  const stream = new ReadableStream({
    start(controller) {
      // 1. Send initial connection confirmation
      const initPayload = JSON.stringify({
        type: "connected",
        userId: user.id,
        deviceId: deviceId || null,
        timestamp: new Date().toISOString(),
      });
      controller.enqueue(encoder.encode(`event: init\ndata: ${initPayload}\n\n`));

      // 2. Subscribe to real-time sync events for this user (and linked email)
      const unsubscribe = subscribeToSyncEvents(user.id, (syncDelta) => {
        // If the event was generated by the same device, we can still forward it or let client know
        try {
          const dataString = JSON.stringify(syncDelta);
          controller.enqueue(encoder.encode(`event: sync\ndata: ${dataString}\n\n`));
        } catch (err) {
          console.warn("[SSE Stream] Failed to enqueue event:", err);
        }
      }, user.email);

      // 3. Heartbeat interval to prevent proxy or Cloud Run idle connection timeouts
      const heartbeatInterval = setInterval(() => {
        try {
          controller.enqueue(encoder.encode(`:keepalive ${Date.now()}\n\n`));
        } catch {
          clearInterval(heartbeatInterval);
        }
      }, 15000);

      // 4. Clean up on disconnect / abort
      req.signal.addEventListener("abort", () => {
        clearInterval(heartbeatInterval);
        unsubscribe();
        try {
          controller.close();
        } catch {}
      });
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "text/event-stream; charset=utf-8",
      "Cache-Control": "no-cache, no-transform, no-store, must-revalidate",
      Connection: "keep-alive",
      "X-Accel-Buffering": "no", // Disables Nginx buffering for low-latency streaming
    },
  });
}
